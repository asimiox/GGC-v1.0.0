    private fun normalizeDeptName(raw: String): String {
        val lower = raw.lowercase().trim()
        return when {
            "comp" in lower || "info" in lower || "it" == lower || "cs" == lower -> "Information Technology"
            "phy" in lower -> "Physics"
            "chem" in lower -> "Chemistry"
            "eng" in lower -> "English"
            "eco" in lower -> "Economics"
            "math" in lower -> "Mathematics"
            "zoo" in lower -> "Zoology"
            "pol" in lower -> "Political Science"
            "urd" in lower -> "Urdu"
            "isl" in lower -> "Islamiyat"
            "bba" in lower || "busi" in lower || "comm" in lower -> "BBA"
            "stat" in lower -> "Statistics"
            "bot" in lower -> "Botany"
            "hist" in lower -> "History"
            "pers" in lower -> "Persian"
            "edu" in lower -> "Education"
            "admin" in lower || "staff" in lower || "office" in lower -> "Administrative Staff"
            else -> raw
        }
    }

    fun getFacultyByDepartment(department: String): List<FacultyMember> {
        val norm = normalizeDeptName(department)
        if (norm == "Administrative Staff") {
            return adminStaffList
        }
        val matched = facultyList.filter { 
            normalizeDeptName(it.department).equals(norm, ignoreCase = true) ||
            it.department.contains(department, ignoreCase = true) ||
            department.contains(it.department, ignoreCase = true)
        }
        return if (matched.isNotEmpty()) matched else {
            facultyList.filter { it.department.equals(department, ignoreCase = true) }
        }
    }

    fun getFacultyForDepartments(departments: List<String>): List<FacultyMember> {
        val normalizedList = departments.map { normalizeDeptName(it) }
        return facultyList.filter { member ->
            val mNorm = normalizeDeptName(member.department)
            normalizedList.any { it.equals(mNorm, ignoreCase = true) }
        }
    }

    fun getAllDepartments(): List<String> {
        return (facultyList.map { it.department }.distinct() + listOf("Administrative Staff")).sorted()
    }

    fun getHodForDepartment(department: String): FacultyMember? {
        val deptFaculty = getFacultyByDepartment(department)
        return deptFaculty.firstOrNull { it.isHod } ?: deptFaculty.firstOrNull()
    }

    fun getPrincipal(): FacultyMember? {
        return facultyList.firstOrNull { it.isPrincipal }
    }

    fun getVicePrincipal(): FacultyMember? {
        return facultyList.firstOrNull { it.isVicePrincipal }
    }

    fun getFacultyForProgramId(programId: String): List<FacultyMember> {
        return when (programId) {
            "bs_it", "ics", "bscs" -> getFacultyByDepartment("Information Technology")
            "bs_bba" -> getFacultyByDepartment("BBA")
            "bs_english", "bseng" -> getFacultyByDepartment("English")
            "bs_islamic_studies", "bsisl" -> getFacultyByDepartment("Islamiyat")
            "bs_physics", "bsphy" -> getFacultyByDepartment("Physics")
            "bs_mathematics", "bsmath" -> getFacultyByDepartment("Mathematics")
            "bs_political_science", "bspol" -> getFacultyByDepartment("Political Science")
            "bs_urdu", "bsurdu" -> getFacultyByDepartment("Urdu")
            "bs_chemistry", "bschem" -> getFacultyByDepartment("Chemistry")
            "bs_zoology", "bszoo" -> getFacultyByDepartment("Zoology")
            "bs_economics", "bseco" -> getFacultyByDepartment("Economics")
            "fsc_pre_eng" -> getFacultyForDepartments(listOf("Physics", "Mathematics", "Chemistry"))
            "fsc_pre_med" -> getFacultyForDepartments(listOf("Chemistry", "Zoology", "Botany"))
            "fa" -> getFacultyForDepartments(listOf("English", "Urdu", "Islamiyat", "Political Science", "History", "Economics", "Education", "Persian"))
            "icom" -> getFacultyForDepartments(listOf("BBA", "Economics", "Statistics"))
            else -> emptyList()
        }
    }
